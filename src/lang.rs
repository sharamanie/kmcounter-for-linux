//! 界面文案（中/英），对应原版的 MultiLanguage 段。

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Lang {
    Zh,
    En,
}

impl Lang {
    pub fn resolve(cfg_lang: &str) -> Lang {
        match cfg_lang {
            "zh" => return Lang::Zh,
            "en" => return Lang::En,
            _ => {}
        }
        // auto：跟随系统 LANG
        if let Ok(l) = std::env::var("LANG") {
            if l.to_lowercase().starts_with("zh") {
                return Lang::Zh;
            }
        }
        #[cfg(windows)]
        {
            // Windows 下看系统 UI 语言（GetUserDefaultUILanguage）。
            // 注意：Windows 没有 SYSTEM_LANGUAGE 这个环境变量，之前读它等于永远落到英文。
            // LANGID 的低 10 位是主语言 ID，0x04 = 中文（含简繁、港澳、新加坡）
            let langid = unsafe { windows_sys::Win32::Globalization::GetUserDefaultUILanguage() };
            if langid & 0x03ff == 0x04 {
                return Lang::Zh;
            }
        }
        Lang::En
    }

    /// 中文界面需要 CJK 字体，缺字体时退回英文
    pub fn downgrade_if_no_cjk(self, has_cjk: bool) -> Lang {
        match self {
            Lang::Zh if !has_cjk => {
                log::warn!("未找到中文字体，界面退回英文。可在配置中指定 font_path。");
                Lang::En
            }
            other => other,
        }
    }
}

